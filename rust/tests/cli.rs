use std::fs;
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

fn temp_dir(prefix: &str) -> std::path::PathBuf {
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let dir = std::env::temp_dir().join(format!("{prefix}-{}-{nonce}", std::process::id()));
    fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn test_cli_version_and_help() {
    let plus_a = env!("CARGO_BIN_EXE_plus-a");

    let version = Command::new(plus_a).arg("--version").output().unwrap();
    assert!(version.status.success());
    let ver_str = String::from_utf8_lossy(&version.stdout);
    let expected_version = format!("+a {}", env!("CARGO_PKG_VERSION"));
    assert!(ver_str.starts_with(&expected_version));

    let help = Command::new(plus_a).arg("--help").output().unwrap();
    assert!(help.status.success());
    let help_str = String::from_utf8_lossy(&help.stdout);
    assert!(help_str.contains("ASCENSION +A"));
    assert!(help_str.contains(".pa"));
    assert!(help_str.contains("+a <source.pa>"));
    assert!(help_str.contains("+a run"));
    assert!(help_str.contains("+a build"));
    assert!(help_str.contains("+a check"));
}

#[test]
fn test_cli_direct_execution_pa() {
    let plus_a = env!("CARGO_BIN_EXE_plus-a");
    let dir = temp_dir("test-direct-exec");
    let source_path = dir.join("test_program.pa");
    let build_dir = dir.join("build");

    fs::write(
        &source_path,
        "unit test_direct\nexport main\nmain::\n    move R0.q <- 77\n    stop\n",
    )
    .unwrap();

    let output = Command::new(plus_a)
        .arg(&source_path)
        .arg("--build-dir")
        .arg(&build_dir)
        .output()
        .unwrap();

    assert!(
        output.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(stdout.contains("stopped: 77"), "stdout: {stdout}");

    // Verify generated bytecode was saved into build/bytecode/ and not in source dir
    assert!(build_dir.join("bytecode/test_program.avm").exists());
    assert!(!dir.join("test_program.avm").exists());

    fs::remove_dir_all(dir).unwrap();
}

