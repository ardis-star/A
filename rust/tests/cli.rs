#[test]
fn test_cli_build_subcommand() {
    let plus_a = env!("CARGO_BIN_EXE_plus-a");
    let dir = temp_dir("test-build");
    let source_path = dir.join("builder.pa");
    let build_dir = dir.join("my_build");

    fs::write(
        &source_path,
        "unit builder\nexport main\nmain::\n    move R0.q <- 10\n    return\n",
    )
    .unwrap();

    // Build without executing
    let output = Command::new(plus_a)
        .arg("build")
        .arg(&source_path)
        .arg("--build-dir")
        .arg(&build_dir)
        .output()
        .unwrap();

    assert!(output.status.success());
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(stdout.contains("built:"));
    assert!(stdout.contains("builder.avm"));

    // File exists in my_build/bytecode/builder.avm
    assert!(build_dir.join("bytecode/builder.avm").exists());
    // Source directory was not polluted
    assert!(!dir.join("builder.avm").exists());

    // Build with explicit -o
    let custom_output = dir.join("specific/custom.avm");
    let output2 = Command::new(plus_a)
        .arg("build")
        .arg(&source_path)
        .arg("-o")
        .arg(&custom_output)
        .output()
        .unwrap();
    assert!(output2.status.success());
    assert!(custom_output.exists());

    fs::remove_dir_all(dir).unwrap();
}

#[test]
fn test_cli_check_subcommand() {
    let plus_a = env!("CARGO_BIN_EXE_plus-a");
    let dir = temp_dir("test-check");
    let valid_path = dir.join("valid.pa");
    let invalid_path = dir.join("invalid.pa");

    fs::write(
        &valid_path,
        "unit valid\nexport main\nmain::\n    move R0.q <- 1\n    return\n",
    )
    .unwrap();

    fs::write(
        &invalid_path,
        "unit invalid\nexport main\nmain::\n    sum R0.d <- R1.q, 1\n",
    )
    .unwrap();

    // Valid check succeeds and writes no files
    let output_valid = Command::new(plus_a)
        .arg("check")
        .arg(&valid_path)
        .output()
        .unwrap();
    assert!(output_valid.status.success());
    assert!(String::from_utf8_lossy(&output_valid.stdout).contains("checked:"));
    assert!(!dir.join("valid.avm").exists());
    assert!(!dir.join("build").exists());

    // Invalid check fails with file, line, col
    let output_invalid = Command::new(plus_a)
        .arg("check")
        .arg(&invalid_path)
        .output()
        .unwrap();
    assert_eq!(output_invalid.status.code(), Some(2));
    let stderr = String::from_utf8_lossy(&output_invalid.stderr);
    assert!(stderr.contains("invalid.pa:4:5:"));
    assert!(stderr.contains("widths must match"));

    fs::remove_dir_all(dir).unwrap();
}

#[test]
fn test_cli_extension_validation() {
    let plus_a = env!("CARGO_BIN_EXE_plus-a");
    let dir = temp_dir("test-ext");

    // 1. Rejection of .ma (-A is not supported)
    let ma_path = dir.join("test.ma");
    fs::write(&ma_path, "unit test\n").unwrap();

    for cmd in &[
        vec![ma_path.to_str().unwrap()],
        vec!["run", ma_path.to_str().unwrap()],
        vec!["build", ma_path.to_str().unwrap()],
        vec!["check", ma_path.to_str().unwrap()],
    ] {
        let output = Command::new(plus_a).args(cmd).output().unwrap();
        assert_eq!(output.status.code(), Some(2));
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert!(stderr.contains("unsupported file extension '.ma'"));
        assert!(stderr.contains("'-A' is not supported"));
    }

    // 2. Rejection of non-.pa extensions
    let txt_path = dir.join("test.txt");
    fs::write(&txt_path, "unit test\n").unwrap();

    let output_txt = Command::new(plus_a).arg(&txt_path).output().unwrap();
    assert_eq!(output_txt.status.code(), Some(2));
    let stderr_txt = String::from_utf8_lossy(&output_txt.stderr);
    assert!(stderr_txt.contains("invalid file extension '.txt'"));
    assert!(stderr_txt.contains(".pa"));

    // 3. Acceptance of .pa
    let pa_path = dir.join("test.pa");
    fs::write(&pa_path, "unit test\nexport main\nmain::\n    return\n").unwrap();
    let output_pa = Command::new(plus_a).arg(&pa_path).output().unwrap();
    assert!(output_pa.status.success());

    fs::remove_dir_all(dir).unwrap();
}

