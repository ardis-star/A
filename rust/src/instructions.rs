#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shape {
    NoArgs,
    Branch,
    Call,
    Two,
    DestinationSource,
    DestinationTwo,
    DestinationTwoSourceTwo,
    FlagSet,
    Address,
    CompareSwap,
    MemoryLoad,
    MemoryStore,
    Select,
    Sys,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Definition {
    pub opcode: u16,
    pub shape: Shape,
    pub width: bool,
}

pub fn definition(name: &str) -> Option<Definition> {
    use Shape::*;
    let (opcode, shape, width) = match name {
        "nop" => (0x0001, NoArgs, false),
        "break" => (0x0002, NoArgs, false),
        "return" => (0x0003, NoArgs, false),
        "stop" => (0x0004, NoArgs, false),
        "div.u" => (0x0005, DestinationTwoSourceTwo, true),
        "div.s" => (0x0006, DestinationTwoSourceTwo, true),
        "catch" => (0x0007, Branch, false),
        "uncatch" => (0x0008, NoArgs, false),
        "raise" => (0x0009, FlagSet, false),
        "flag.direction" => (0x000A, FlagSet, false),
        "address" => (0x000B, Address, true),
        "fence" => (0x000C, FlagSet, false),
        "compare.swap" => (0x000D, CompareSwap, true),
        "move" => (0x0010, DestinationSource, true),
        "extend.s" => (0x0011, DestinationSource, true),
        "extend.z" => (0x0012, DestinationSource, true),
        "select" => (0x0013, Select, true),
        "sum" => (0x0020, DestinationTwo, true),
        "sum!" => (0x0021, DestinationTwo, true),
        "diff" => (0x0022, DestinationTwo, true),
        "diff!" => (0x0023, DestinationTwo, true),
        "compare!" => (0x0024, Two, true),
        "sumc" => (0x0025, DestinationTwo, true),
        "sumc!" => (0x0026, DestinationTwo, true),
        "diffc" => (0x0027, DestinationTwo, true),
        "diffc!" => (0x0028, DestinationTwo, true),
        "mul" => (0x0029, DestinationTwo, true),
        "mul!" => (0x002a, DestinationTwo, true),
        "checked.sum" => (0x002b, DestinationTwo, true),
        "neg" => (0x002c, DestinationSource, true),
        "neg!" => (0x002d, DestinationSource, true),
        "inc" => (0x002e, DestinationSource, true),
        "inc!" => (0x002f, DestinationSource, true),
        "and" => (0x0030, DestinationTwo, true),
        "and!" => (0x0031, DestinationTwo, true),
        "or" => (0x0032, DestinationTwo, true),
        "or!" => (0x0033, DestinationTwo, true),
        "xor" => (0x0034, DestinationTwo, true),
        "xor!" => (0x0035, DestinationTwo, true),
        "dec" => (0x0036, DestinationSource, true),
        "dec!" => (0x0037, DestinationSource, true),
        "not" => (0x0038, DestinationSource, true),
        "not!" => (0x0039, DestinationSource, true),
        "shift.l" => (0x003a, DestinationTwo, true),
        "shift.l!" => (0x003b, DestinationTwo, true),
        "shift.r" => (0x003c, DestinationTwo, true),
        "shift.r!" => (0x003d, DestinationTwo, true),
        "shift.ar" => (0x003e, DestinationTwo, true),
        "shift.ar!" => (0x003f, DestinationTwo, true),
        "load.u8" => (0x0040, MemoryLoad, true),
        "load.u16" => (0x0041, MemoryLoad, true),
        "load.u32" => (0x0042, MemoryLoad, true),
        "load.u64" => (0x0043, MemoryLoad, true),
        "store.u8" => (0x0044, MemoryStore, true),
        "store.u16" => (0x0045, MemoryStore, true),
        "store.u32" => (0x0046, MemoryStore, true),
        "store.u64" => (0x0047, MemoryStore, true),
        "load.acquire.u8" => (0x0080, MemoryLoad, true),
        "load.acquire.u16" => (0x0081, MemoryLoad, true),
        "load.acquire.u32" => (0x0082, MemoryLoad, true),
        "load.acquire.u64" => (0x0083, MemoryLoad, true),
        "store.release.u8" => (0x0084, MemoryStore, true),
        "store.release.u16" => (0x0085, MemoryStore, true),
        "store.release.u32" => (0x0086, MemoryStore, true),
        "store.release.u64" => (0x0087, MemoryStore, true),
        "rotate.l" => (0x0048, DestinationTwo, true),
        "rotate.l!" => (0x0049, DestinationTwo, true),
        "rotate.r" => (0x004a, DestinationTwo, true),
        "rotate.r!" => (0x004b, DestinationTwo, true),
        "bit.set" => (0x004c, DestinationTwo, true),
        "bit.clear" => (0x004d, DestinationTwo, true),
        "bit.test!" => (0x004e, Two, true),
        "jump" => (0x0050, Branch, false),
        "if.zero" => (0x0051, Branch, false),
        "if.notzero" => (0x0052, Branch, false),
        "if.carry" => (0x0053, Branch, false),
        "if.nocarry" => (0x0054, Branch, false),
        "if.sign" => (0x0061, Branch, false),
        "if.notsign" => (0x0062, Branch, false),
        "if.overflow" => (0x0063, Branch, false),
        "if.nooverflow" => (0x0064, Branch, false),
        "if.even" => (0x0065, Branch, false),
        "if.odd" => (0x0066, Branch, false),
        "call" => (0x0055, Call, false),
        "tailcall" => (0x0056, Call, false),
        "sys.region.map" => (0x0057, Sys, false),
        "sys.region.unmap" => (0x0058, Sys, false),
        "sys.port.read" => (0x0059, Sys, false),
        "sys.port.write" => (0x005A, Sys, false),
        "sys.irq.bind" => (0x005B, Sys, false),
        "sys.irq.enable" => (0x005C, Sys, false),
        "sys.irq.disable" => (0x005D, Sys, false),
        "sys.context.enter" => (0x005E, Sys, false),
        "sys.context.return" => (0x005F, Sys, false),
        "exchange" => (0x0060, Two, false),
        "sys.cpu.control" => (0x0067, Sys, false),
        "sys.power" => (0x0068, Sys, false),
        _ => return None,
    };
    Some(Definition {
        opcode,
        shape,
        width,
    })
}

