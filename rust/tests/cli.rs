#[cfg(all(target_arch = "x86_64", target_os = "linux"))]
#[test]
fn test_cli_build_and_run_native() {
    let plus_a = env!("CARGO_BIN_EXE_plus-a");
    let dir = temp_dir("test-native");
    let source_path = dir.join("native_prog.pa");
    let build_dir = dir.join("native_build");

    fs::write(
        &source_path,
        "unit native_prog\nexport main\nmain::\n    move R0.q <- 55\n    stop\n",
    )
    .unwrap();

    // 1. Build native
    let build_out = Command::new(plus_a)
        .arg("build")
        .arg(&source_path)
        .arg("--native")
        .arg("--build-dir")
        .arg(&build_dir)
        .output()
        .unwrap();
    assert!(
        build_out.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&build_out.stderr)
    );
    let exe_path = build_dir.join("native/native_prog");
    assert!(exe_path.exists());

    // 2. Run native executable directly
    let exe_status = Command::new(&exe_path).status().unwrap();
    assert_eq!(exe_status.code(), Some(55));

    // 3. Run --native via CLI
    let run_out = Command::new(plus_a)
        .arg("run")
        .arg(&source_path)
        .arg("--native")
        .arg("--build-dir")
        .arg(&build_dir)
        .output()
        .unwrap();
    assert!(run_out.status.success());
    assert!(String::from_utf8_lossy(&run_out.stdout).contains("stopped: 55"));

    fs::remove_dir_all(dir).unwrap();
}

